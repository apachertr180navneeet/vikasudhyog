    /**
     * Retrieve the current active settings for a company or global default.
     */
    public static function getEffectiveSettings(?int $companyId = null): self
    {
        $query = static::query();
        if ($companyId) {
            $query->where('company_id', $companyId);
        }

        $setting = $query->first();

        if (!$setting) {
            $defaults = static::defaultTemplates();
            $setting = static::create([
                'company_id'             => $companyId,
                'provider'               => 'meta_cloud_api',
                'phone_number_id'        => '104859201948271',
                'waba_id'                => '109284729104857',
                'access_token'           => 'EAAG...SAMPLE_TOKEN...Z3B',
                'display_phone_number'   => '+91 98290 12345',
                'webhook_verify_token'   => 'vu_wa_verify_token_2026',
                'is_enabled'             => true,
                'sandbox_mode'           => true,
                'monthly_quota'          => 5000,
                'credits_used'           => 4825,
                'auto_send_invoice'      => true,
                'auto_send_order'        => true,
                'auto_send_dispatch'     => true,
                'auto_send_receipt'      => true,
                'auto_send_due_reminder' => false,
                'invoice_template'       => $defaults['invoice'],
                'order_template'         => $defaults['order'],
                'dispatch_template'      => $defaults['dispatch'],
                'receipt_template'       => $defaults['receipt'],
                'due_reminder_template'  => $defaults['due_reminder'],
            ]);
        }

        return $setting;
    }
}
