<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;

class WhatsAppSetting extends Model
{
    use HasFactory;

    protected $table = 'whatsapp_settings';

    protected $fillable = [
        'company_id',
        'provider',
        'phone_number_id',
        'waba_id',
        'access_token',
        'display_phone_number',
        'webhook_verify_token',
        'is_enabled',
        'sandbox_mode',
        'monthly_quota',
        'credits_used',
        'auto_send_invoice',
        'auto_send_order',
        'auto_send_dispatch',
        'auto_send_receipt',
        'auto_send_due_reminder',
        'invoice_template',
        'order_template',
        'dispatch_template',
        'receipt_template',
        'due_reminder_template',
    ];

    protected $casts = [
        'is_enabled'             => 'boolean',
        'sandbox_mode'           => 'boolean',
        'auto_send_invoice'      => 'boolean',
        'auto_send_order'        => 'boolean',
        'auto_send_dispatch'     => 'boolean',
        'auto_send_receipt'      => 'boolean',
        'auto_send_due_reminder' => 'boolean',
        'monthly_quota'          => 'integer',
        'credits_used'           => 'integer',
    ];

    public function company()
    {
        return $this->belongsTo(Company::class);
    }

